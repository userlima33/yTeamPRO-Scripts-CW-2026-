local restrictedCountries = {
    ["AT"] = true,
    ["TR"] = false
}
-- --
function banPlayer2()
	local playerName = getPlayerName(source)
	local theSerial = getPlayerSerial(source)
	for _, serial in ipairs(bannedSerials) do
		if theSerial == serial then
			triggerEvent("insertTheFuckingSerialforspoofer", root,player,2397600000)
			banPlayer(source, true)
			outputChatBox("#ffffff* #CCA95A[Auto-Ban] #CCA95A"..playerName.." #ffffffhas benn banned!", source)
			exports["discord"]:msgs("**[Auto-Ban] "..playerName.." has benn banned "..theSerial.."**",getServerPort())
			return
		end
	end
end
-- --
function checkCountry()
	local country = exports.admin:getPlayerCountry(source) or "N/A"
	if restrictedCountries[country] then
		local isWhitelisted = false
		local playerSerial = getPlayerSerial(source)
		for _, serial in ipairs(whitelist) do
			if playerSerial == serial then
				isWhitelisted = true
				break
			end
		end
		if not isWhitelisted then
		local playerName = getPlayerName(source)
			kickPlayer(source, "[Anti-Spoofer] Please contact with the Developer!")
			outputChatBox("#ffffff* #CCA95A[Anti-Spoofer] #CCA95A" ..playerName.. " #ffffffhas been kicked!", getRootElement(), 255, 0, 0)
			exports["discord"]:msgs("**[Anti-Spoofer] "..playerName.." has been kicked** ("..playerSerial..")",getServerPort())	
		end
	end
end
